export const stageKey = stage => `f${String(Math.max(1, Math.floor(Number(stage) || 1))).padStart(2, '0')}`;
export const hasPaintedMap = stage => Boolean(PAINTED[stageKey(stage)]);
export const mapForStage = stage => PAINTED[stageKey(stage)] || DEFAULT_MAP;

export function pointOnPath(distance, map = DEFAULT_MAP) {
  let remaining = Math.max(0, distance);
  for (const segment of map.segments) {
    if (remaining <= segment.length) {
      const fraction = remaining / segment.length;
      return {
        x: segment.from.x + (segment.to.x - segment.from.x) * fraction,
        y: segment.from.y + (segment.to.y - segment.from.y) * fraction,
      };
    }
    remaining -= segment.length;
  }
  return { ...map.path[map.path.length - 1] };
}
