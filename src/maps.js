/** Enemy roads and tower platforms, in the 1000 × 600 battle space. No DOM access. */
const build = (path, pads) => {
  const points = path.map(([x, y]) => ({ x, y }));
  const segments = points.slice(1).map((point, index) => ({
    from: points[index], to: point,
    length: Math.hypot(point.x - points[index].x, point.y - points[index].y),
  }));
  return Object.freeze({
    width: 1000, height: 600, path: points, segments,
    pathLength: segments.reduce((total, segment) => total + segment.length, 0),
    pads: pads.map(([x, y], index) => ({ id: `p${index + 1}`, x, y })),
  });
};

